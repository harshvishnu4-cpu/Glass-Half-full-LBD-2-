// Generates js/preload-manifest.js — the loading bar's size table — from the
// REAL files on disk (assets/** + audio/**), so progress weighting is exact.
// Also cross-references every asset against index.html/css/js and reports any
// file nothing points at (and any reference with no file). Re-run after any
// asset change: node tools/gen-manifest.js
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SCAN_DIRS = ['assets', 'audio'];
const code = ['index.html', 'css/style.css', 'js/game.js', 'js/sfx.js']
  .map((f) => fs.readFileSync(path.join(ROOT, f), 'utf8')).join('\n');

const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = dir + '/' + e.name;
    if (e.isDirectory()) walk(rel);
    else files.push(rel);
  }
})(SCAN_DIRS[0]);
(function walk(dir) {
  for (const e of fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true })) {
    const rel = dir + '/' + e.name;
    if (e.isDirectory()) walk(rel);
    else files.push(rel);
  }
})(SCAN_DIRS[1]);

// a file counts as referenced if code mentions its basename, or its stem —
// some paths are built dynamically, e.g. playSample('cash-register') resolves
// to audio/cash-register.ogg, so match on the bare stem as well as the basename
const unreferenced = files.filter((f) => {
  const base = path.basename(f);
  return !code.includes(base) && !code.includes("'" + base.replace(/\.\w+$/, "'"));
});
if (unreferenced.length) {
  console.log('UNREFERENCED FILES (not in manifest):');
  unreferenced.forEach((f) => console.log('  ' + f));
}

// every asset path mentioned in code must exist on disk (no 404s)
const refs = code.match(/(assets|audio)\/[\w./-]+\.(webp|svg|webm|ogg|woff2)/g) || [];
const missing = [...new Set(refs.map((r) => r.replace(/^\.\.\//, '')))]
  .filter((r) => !fs.existsSync(path.join(ROOT, r)));
if (missing.length) {
  console.log('REFERENCED BUT MISSING (would 404):');
  missing.forEach((f) => console.log('  ' + f));
}

const manifest = files
  .filter((f) => !unreferenced.includes(f))
  .map((f) => ({ u: f, b: fs.statSync(path.join(ROOT, f)).size }))
  .sort((a, b) => a.b - b.b);

const out = '/* AUTO-GENERATED by tools/gen-manifest.js — real on-disk sizes for\n' +
  '   byte-accurate loading-bar progress. Regenerate after any asset change. */\n' +
  'window.PRELOAD_MANIFEST = ' + JSON.stringify(manifest, null, 0).replace(/\},\{/g, '},\n{') + ';\n';
fs.writeFileSync(path.join(ROOT, 'js', 'preload-manifest.js'), out);
console.log('manifest: ' + manifest.length + ' files, ' +
  Math.round(manifest.reduce((s, f) => s + f.b, 0) / 1024) + 'KB total');
process.exit(missing.length ? 1 : 0);
